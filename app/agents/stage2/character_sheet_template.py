"""角色设定表提示词模板（用户 2026-10-07 定稿的固定格式）。

## 版式（不许改）

```
┌──────────────┬─────────┬─────────┬─────────┐
│              │         │         │         │
│  正脸放大     │  正面   │  侧面   │  背面   │
│  （≈1/3 宽）  │  全身   │  全身   │  全身   │
│              │         │         │         │
└──────────────┴─────────┴─────────┴─────────┘
                   16 : 9
```

## 为什么用**一次生成 16:9**，而不是"4 张独立生成 + 拼接"

两条路都实跑过（2026-10-07）：

| | 一次生成 16:9 | 4 张独立 + 拼接 |
|---|---|---|
| 布局 | ✅ 一次到位，完全符合版式 | ⚠️ 要逐格写死取景才能对齐，否则脸图成中景、三格大小不一 |
| 一致性 | ✅ **同一张图里生成，天然同一人** | ⚠️ 四张独立生成 → 脸/服装会漂（实测侧视像另一个人） |
| 细节 | 中等（每格 ~250px） | 高（每格原图 768×1024） |
| 耗时 | **29 秒 / 1 张** | 28 秒 × 4 = **112 秒** |

**结论**：设定表用**一次生成** —— 用户要的是一张「给人看的设定图」，
版式准确 + 一致性 比单格像素更重要。要单张高清参考图时另走
`character_designer` 的单视角路径（或 `character_sheet.compose_character_sheet` 拼接）。

## 硬约束（漏一条就出不来）

1. **同一角色、同一套发型和服装** —— 必须明写，否则四个视角会变成四个人
2. **站姿自然、双手自然下垂** —— 否则每格姿势乱、不像设定图
3. **发夹/配饰位置逐视角保持一致** —— 不一致等于资产作废
4. **浅灰偏白影棚背景 + 柔和自然阴影 + 大量留白** —— 拼图时底色统一

## 实测记录

  · 尺寸 1216×688（16:9）→ 每格约 250px 宽；**29~42 秒**
  · 侧脸要**写足**：只写 `side view, profile` 会退化成 3/4 角
  · 负面词里必须有 `text/letters/words/chinese characters` ——
    否则模型会往图上写标注，而它写不对中文，产出乱码
"""

from __future__ import annotations

#: 设定表尺寸（16:9）。
#:
#: ## 为什么从 1216×688 提到 1920×1080
#:
#: 用户问"像素会不会太低了"——**对，偏低**。算每格实际像素：
#:
#:     1216×688  → 每格全身 261×684  = 把 768×1024 缩到 261×348（**单视角图的 23%**）
#:     1920×1080 → 每格全身 416×1088 = 缩到 416×555（**57%**）
#:
#: 实测 1920×1080（77 秒，8GB 显存够用）：蕾丝纹理、发丝、裙褶、鞋面细节
#: 都明显更清楚。1216 那档是我为"29 秒出图"选的，偏小了。
#:
#: 耗时（实测）：1216→29s、1536→43s、1920→77s。
#: 想快可以降到 1536×864（每格 332×864，单视角图的 36%）。
SHEET_SIZE = (1920, 1080)

#: 固定版式模板。占位符只有 3 个：`{name}` / `{appearance}` / `{style}`。
#:
#: ## 每一句都对应一个实测踩过的坑（别删）
#:
#: · 「**从左到右依次是**正面、侧面、背面」—— 漏了它，模型会在高分辨率下
#:   自己重排顺序（实测出成 正/背/侧）。
#: · 「**全身完整入画、从头顶到脚**」—— 漏了它，脚会被裁掉、三格拼不齐。
#: · 「**双手自然下垂 / 手臂不要交叉**」—— 漏了它，模型会把手背到身后或
#:   交叉抱臂，三格姿势不一致。
#: · 「**看不到脸 / 脚尖朝外**」—— 背面视图的专属约束。漏了它，背面视图
#:   的脚仍然朝前（实测）。
#: · 「**侧身 90 度 / 只露出一只眼睛**」—— 漏了它，侧面会退化成 3/4 角（实测）。
#: · 「**不要画任何边框或分隔线**」—— 漏了它，边缘会出现一圈细黑框（实测）。
SHEET_TEMPLATE = """生成一张{style_prefix}角色设定图（character design sheet），横幅 16:9 构图。
画面布局：左侧是一张占画面约**三分之一**宽的大尺寸面部特写，
右侧三格并排站立同一个角色的正面全身、侧面全身、背面全身三个视图，
从左到右依次是正面、侧面、背面。
右侧三格比左侧脸特写更宽，**每格必须容纳一个完整的人**。
三个视图必须是完全同一个角色、同一套发型和服装。
每格用远景全身构图：从头顶到脚底全部入画、鞋必须完整可见、不裁脚，
人物高度约占格高的九成，水平居中，四周留白。
站姿自然，双手自然下垂，手臂不要交叉，不要画任何边框或分隔线。
侧面视图必须是侧身 90 度、只露出一只眼睛的真侧脸；
背面视图必须是完全背对镜头、看不到脸，双脚脚尖朝外。
角色：{name}。{appearance}
{style}
{render_tail}"""

#: 版式尾段（渲染质感通用要求）。用户给的写法里这段很具体，照收。
SHEET_RENDER_TAIL = (
    "整体为精致 3D 渲染质感，类似 BJD 人偶的精致五官，浅灰偏白影棚背景，"
    "柔和自然阴影，8K，精细发丝和蕾丝材质，高级时尚大片质感，"
    "画面干净克制、大量留白。"
)

#: 默认风格/镜头段（与角色无关，可整体替换）。
#: ⚠️ 用户明确要求「提示词不要压缩」—— 所以这段保留全部限定词，
#: 别为了"简洁"删掉 85mm / 珍珠质感 / 柔和轮廓光。
SHEET_STYLE = "85mm 人像镜头，柔和珍珠质感轮廓光，高级时尚大片质感。"

#: 标题里的风格前缀（由 `style_prefix` 控制，默认 3D 写实动漫风）
SHEET_STYLE_PREFIX = "3D 写实风格的动漫女性"

#: 负面提示词。三组各有用途，**都不能删**：
#:
#: 一、防**乱码**：`text/letters/words/chinese characters/watermark/...`
#:     —— 模型写不对中文，漏这组就往图上写标注。
#: 二、防**四个视角变成四个人**：`duplicated character/inconsistent face/...`
#: 三、防**边框与分隔线**：`border/frame/divider/outline`
#:     —— 实测高分辨率下边上会出现一圈细黑框。
SHEET_NEGATIVE = (
    "multiple panels beyond the layout, duplicated character, inconsistent face, "
    "different person, mismatched outfit, text, letters, words, chinese characters, "
    "watermark, signature, logo, caption, annotation, arrows, grid lines, "
    "border, frame, thin border, black frame, picture frame, vignette, divider, "
    "extra limbs, extra fingers, deformed hands, bad anatomy, "
    "blurry, lowres, jpeg artifacts"
)

#: `{appearance}` 建议的**七段结构**（颗粒度基准）。
#: 每段要具体到能画出来；含糊的形容词（"很漂亮""有气质"）模型只会平均化，
#: 四个视角就全不一样了。
#:
#: 这套结构是从用户 2026-10-07 给的示例里提炼的 —— 他明确要求
#: 「提示词不要压缩」，所以这里的每一段都对应他原文里的一个层次。
APPEARANCE_SECTIONS = (
    "1. 气质基调：年龄/性别/整体气质，如「年轻东方女性，清冷柔美，带轻甜酷和梦幻少女感」",
    "2. 面部（逐部位）：肤色（含质感，如「哑光质感、干净无暇」）→脸型→眉（形状/走向）→"
    "眼（形状/颜色/神态/卧蚕/睫毛/眼妆配色/下眼睑，如「下眼睑有轻微的哭红感」）→"
    "鼻（如「窄直高挺、鼻头小巧」）→唇（颜色/形状/开合，如「水润玫瑰豆沙色、饱满、微微微张」）",
    "3. 发型：颜色→长度→发量→卷度→光泽→刘海→侧发→发饰，"
    "并**显式要求「各视角发型、刘海和发夹位置保持一致」**",
    "4. 服装（分上下身，每件单品都要写全）**品类+颜色+材质+版型+装饰细节**，"
    "如「雾灰色高腰层叠百褶迷你裙，两到三层不规则裙片，下层露出少量粉色内衬，"
    "裙边有细窄蕾丝、小蝴蝶结和银色珠链吊坠装饰，腰部有纤细银色腰链」",
    "5. 配饰（逐个列，顺序：耳→颈→包→袜→鞋）**材质与颜色必须成对出现**"
    "（如「银色金属扣」「粉色水晶」），否则模型自由发挥",
    "6. 身形：如「身材高挑，九头身时装模特比例」",
    "7. 渲染与镜头（与角色无关，可复用）：如「精致 3D 渲染质感，类似 BJD 人偶的精致五官，"
    "85mm 人像镜头，柔和珍珠质感轮廓光，浅灰偏白影棚背景，8K，高级时尚大片质感」",
)


def build_sheet_prompt(
    name: str,
    appearance: str,
    style: str | None = None,
    *,
    style_prefix: str | None = None,
    render_tail: str | None = None,
) -> str:
    """拼出设定表提示词。

    参数：
        name:         角色名
        appearance:   外貌与服装描述（建议按 `APPEARANCE_SECTIONS` 的七段写）
        style:        风格/镜头段；None 用 `SHEET_STYLE`
        style_prefix: 标题里的风格前缀（如「3D 写实风格的动漫女性」）；
                      None 用 `SHEET_STYLE_PREFIX`
        render_tail:  版式尾段（渲染质感通用要求）；None 用 `SHEET_RENDER_TAIL`
    """
    return SHEET_TEMPLATE.format(
        name=(name or "").strip() or "角色",
        appearance=(appearance or "").strip(),
        style=(style if style is not None else SHEET_STYLE).strip(),
        style_prefix=(
            style_prefix if style_prefix is not None else SHEET_STYLE_PREFIX
        ).strip(),
        render_tail=(
            render_tail if render_tail is not None else SHEET_RENDER_TAIL
        ).strip(),
    )
